  // ── Sorted phrase list (longest first) ───────────────────────────────────
  // Built lazily; sorted by key length descending so longer phrases always
  // win over shorter overlapping ones in the substitution pass.
  static List<MapEntry<String, String>>? _sorted;
  static List<MapEntry<String, String>> get _sortedPhrases {
    _sorted ??= _phrases.entries.toList()
      ..sort((a, b) => b.key.length.compareTo(a.key.length));
    return _sorted!;
  }

  // ── Public API ────────────────────────────────────────────────────────────

  /// Translates [input] from Italian to English using the built-in glossary.
  /// Returns the input unchanged if nothing matches (better than a garbled
  /// machine translation of a name that happens to be untranslatable).
  static String translate(String input) {
    if (input.isEmpty) return input;
    final trimmed = input.trim();

    // 1. Exact phrase match
    final exact = _phrases[trimmed.toLowerCase()];
    if (exact != null) return _matchCase(exact, trimmed);

    // 2. Longest-phrase substitution pass
    final phraseResult = _applyPhrases(trimmed);
    if (phraseResult != trimmed) return phraseResult;

    // 3. Word-by-word fallback
    return _wordByWord(trimmed);
  }

  static String? translateOrNull(String? input) =>
      input == null ? null : translate(input);

  // ── Internals ─────────────────────────────────────────────────────────────

  static String _applyPhrases(String input) {
    // Scan for the first (longest) matching phrase and replace it, then recurse.
    final lower = input.toLowerCase();
    for (final entry in _sortedPhrases) {
      final idx = lower.indexOf(entry.key);
      if (idx < 0) continue;
      final before = input.substring(0, idx);
      final after = input.substring(idx + entry.key.length);
      final replacement = _matchCase(entry.value, input.substring(idx, idx + entry.key.length));
      return _applyPhrases(before) + replacement + _applyPhrases(after);
    }
    return input;
  }

  static String _wordByWord(String input) {
    return input.split(RegExp(r'(\s+)')).map((token) {
      if (token.trim().isEmpty) return token; // preserve spacing
      final lower = token.toLowerCase();
      final translated = _words[lower];
      if (translated == null) return token; // unknown word — keep original
      return _matchCase(translated, token);
    }).join();
  }

  /// Preserves the capitalisation style of [original] on [translated].
  static String _matchCase(String translated, String original) {
    if (original.isEmpty || translated.isEmpty) return translated;
    if (original == original.toUpperCase()) return translated.toUpperCase();
    if (original[0] == original[0].toUpperCase()) {
      return translated[0].toUpperCase() + translated.substring(1);
    }
    return translated;
  }
